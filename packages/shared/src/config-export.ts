import type { Device, Link, Vendor } from './types';
import { formatVlanList, parseIpCidr, prefixToMask, toRanges } from './net';

type CfgDevice = Pick<Device, 'id' | 'name' | 'type' | 'mgmtIp' | 'mgmtGateway' | 'mgmtVlan'>;
type CfgLink = Pick<Link, 'id' | 'sourceId' | 'sourcePort' | 'destId' | 'destPort' | 'mode' | 'nativeVlan' | 'destNativeVlan' | 'taggedVlans' | 'accessVlan'>;

interface PortConfig {
  port: string;
  remoteName: string;
  remotePort: string;
  mode: 'access' | 'trunk';
  accessVlan: number | null;
  nativeVlan: number | null;
  tagged: number[];
}

/** Ports of `device` seen from its own side of every link. */
export function portConfigsFor(device: CfgDevice, devices: CfgDevice[], links: CfgLink[]): PortConfig[] {
  const byId = new Map(devices.map((d) => [d.id, d]));
  const out: PortConfig[] = [];
  for (const l of links) {
    const isSource = l.sourceId === device.id;
    const isDest = l.destId === device.id;
    if (!isSource && !isDest) continue;
    const local = isSource
      ? { port: l.sourcePort, native: l.nativeVlan, remoteId: l.destId, remotePort: l.destPort }
      : { port: l.destPort, native: l.destNativeVlan ?? l.nativeVlan, remoteId: l.sourceId, remotePort: l.sourcePort };
    out.push({
      port: local.port,
      remoteName: byId.get(local.remoteId)?.name ?? '?',
      remotePort: local.remotePort,
      mode: l.mode,
      accessVlan: l.accessVlan,
      nativeVlan: local.native,
      tagged: [...(l.taggedVlans ?? [])],
    });
  }
  return out.sort((a, b) => a.port.localeCompare(b.port, undefined, { numeric: true }));
}

function vlanSet(device: CfgDevice, ports: PortConfig[]): number[] {
  const s = new Set<number>();
  if (device.mgmtVlan) s.add(device.mgmtVlan);
  for (const p of ports) {
    if (p.accessVlan) s.add(p.accessVlan);
    if (p.nativeVlan) s.add(p.nativeVlan);
    p.tagged.forEach((v) => s.add(v));
  }
  return [...s].sort((a, b) => a - b);
}

/** Only switch-like devices get switchport commands; routers/firewalls get interface descriptions. */
function isSwitchLike(d: CfgDevice) {
  return d.type === 'switch' || d.type === 'access_point';
}

function sanitizeName(s: string): string {
  // CLI tokens must not contain whitespace/newlines (also prevents config injection via names).
  return s.replace(/[^A-Za-z0-9_.-]+/g, '-').replace(/^-+|-+$/g, '') || 'device';
}
function sanitizeDesc(s: string): string {
  return s.replace(/[\r\n]+/g, ' ').trim();
}

function ciscoLike(vendor: 'cisco' | 'arista', d: CfgDevice, ports: PortConfig[]): string[] {
  const L: string[] = [];
  L.push(`! ${vendor === 'cisco' ? 'Cisco IOS' : 'Arista EOS'} configuration generated by NetForge for ${sanitizeDesc(d.name)}`);
  L.push(`hostname ${sanitizeName(d.name)}`, '!');
  const vlans = vlanSet(d, ports);
  if (isSwitchLike(d)) for (const v of vlans) L.push(`vlan ${v}`, ` name VLAN${v}`, '!');
  const ip = parseIpCidr(d.mgmtIp);
  if (ip && d.mgmtVlan && isSwitchLike(d)) {
    L.push(`interface Vlan${d.mgmtVlan}`, ' description Management');
    L.push(ip.prefix !== null ? ` ip address ${ip.ip} ${prefixToMask(ip.prefix)}` : ` ip address ${ip.ip} 255.255.255.0`, ' no shutdown', '!');
    if (d.mgmtGateway) L.push(vendor === 'cisco' ? `ip default-gateway ${d.mgmtGateway}` : `ip route 0.0.0.0/0 ${d.mgmtGateway}`, '!');
  }
  for (const p of ports) {
    L.push(`interface ${p.port}`, ` description ${sanitizeDesc(`-> ${p.remoteName} ${p.remotePort}`)}`);
    if (isSwitchLike(d)) {
      if (p.mode === 'access') {
        L.push(' switchport mode access');
        if (p.accessVlan) L.push(` switchport access vlan ${p.accessVlan}`);
      } else {
        if (vendor === 'cisco') L.push(' switchport trunk encapsulation dot1q');
        L.push(' switchport mode trunk');
        if (p.nativeVlan) L.push(` switchport trunk native vlan ${p.nativeVlan}`);
        if (p.tagged.length) L.push(` switchport trunk allowed vlan ${formatVlanList([...p.tagged, ...(p.nativeVlan ? [p.nativeVlan] : [])])}`);
      }
    } else if (p.mode === 'trunk') {
      L.push(' ! trunk towards this routed/firewall port: create one sub-interface per tagged VLAN');
      if (p.tagged.length) L.push(` ! tagged VLANs: ${formatVlanList(p.tagged)}`);
    }
    L.push(' no shutdown', '!');
  }
  L.push('end');
  return L;
}

function huawei(d: CfgDevice, ports: PortConfig[]): string[] {
  const L: string[] = [];
  L.push(`# Huawei VRP configuration generated by NetForge for ${sanitizeDesc(d.name)}`);
  L.push(`sysname ${sanitizeName(d.name)}`, '#');
  const vlans = vlanSet(d, ports);
  if (isSwitchLike(d) && vlans.length) L.push(`vlan batch ${vlans.join(' ')}`, '#');
  const ip = parseIpCidr(d.mgmtIp);
  if (ip && d.mgmtVlan && isSwitchLike(d)) {
    L.push(`interface Vlanif${d.mgmtVlan}`, ' description Management');
    L.push(` ip address ${ip.ip} ${ip.prefix !== null ? prefixToMask(ip.prefix) : '255.255.255.0'}`, '#');
    if (d.mgmtGateway) L.push(`ip route-static 0.0.0.0 0.0.0.0 ${d.mgmtGateway}`, '#');
  }
  for (const p of ports) {
    L.push(`interface ${p.port}`, ` description ${sanitizeDesc(`-> ${p.remoteName} ${p.remotePort}`)}`);
    if (isSwitchLike(d)) {
      if (p.mode === 'access') {
        L.push(' port link-type access');
        if (p.accessVlan) L.push(` port default vlan ${p.accessVlan}`);
      } else {
        L.push(' port link-type trunk');
        if (p.nativeVlan) L.push(` port trunk pvid vlan ${p.nativeVlan}`);
        const allowed = [...p.tagged, ...(p.nativeVlan ? [p.nativeVlan] : [])];
        if (allowed.length) {
          const ranges = toRanges(allowed).map(([a, b]) => (a === b ? `${a}` : `${a} to ${b}`));
          L.push(` port trunk allow-pass vlan ${ranges.join(' ')}`);
        }
      }
    }
    L.push('#');
  }
  L.push('return');
  return L;
}

export function generateDeviceConfig(vendor: Vendor, device: CfgDevice, devices: CfgDevice[], links: CfgLink[]): string {
  const ports = portConfigsFor(device, devices, links);
  const lines = vendor === 'huawei' ? huawei(device, ports) : ciscoLike(vendor, device, ports);
  return lines.join('\n') + '\n';
}

/** Configuration of every network device (clients and servers are skipped). */
export function generateClientConfig(vendor: Vendor, devices: CfgDevice[], links: CfgLink[]): string {
  const comment = vendor === 'huawei' ? '#' : '!';
  const targets = devices.filter((d) => d.type !== 'client' && d.type !== 'server');
  return targets
    .map((d) => `${comment} ===== ${sanitizeDesc(d.name)} =====\n${generateDeviceConfig(vendor, d, devices, links)}`)
    .join('\n');
}
